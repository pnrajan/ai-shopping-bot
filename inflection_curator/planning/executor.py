"""Shopping Executor for Inflection Curator.

This module implements the ShoppingExecutor class, which is responsible for
executing the plans generated by the ShoppingPlanner. It takes a plan, runs the
specified tools with the provided arguments, and manages the session context.

Example:
    >>> from inflection_curator.planning import ShoppingExecutor
    >>> tools = {"product_search": ProductSearchTool()}
    >>> executor = ShoppingExecutor(tools)
    >>> plan = {"steps": [{"tool": "product_search", "args": {"query": "laptop"}}]}
    >>> result = executor.run(plan, {})
    >>> print(result)
"""

from typing import Dict, Any


class ShoppingExecutor:
    """Executes planned steps using the shopping tool ecosystem.

    This class takes execution plans from the planner and runs the specified
    tools with the provided arguments, updating the session context as needed.

    Attributes:
        tools (Dict[str, Any]): A dictionary of available tools.
    """

    def __init__(self, tools: dict[str, Any] = None) -> None:
        """Initializes the ShoppingExecutor.

        Args:
            tools: A dictionary of available tools.
        """
        self.tools = tools or {}

    def run(self, plan: dict[str, Any], session_ctx: dict[str, Any]) -> dict[str, Any]:
        """Executes a plan by running the specified tool with arguments.

        Args:
            plan: The plan dictionary with steps from the planner.
            session_ctx: The session context to update with results.

        Returns:
            A dictionary containing the execution result, including the tool
            output and any errors.
        """
        steps = plan.get("steps", [])

        # Handle empty plan (clarification needed)
        if not steps:
            return {
                "tool": None,
                "args": None,
                "output": None,
                "clarify": plan.get(
                    "clarify",
                    "Please provide more details about what you're looking for.",
                ),
            }

        # Execute the single step
        step = steps[0]
        tool_name = step.get("tool")
        args = step.get("args", {})

        # Check if tool exists
        if tool_name not in self.tools:
            return {
                "tool": tool_name,
                "args": args,
                "output": f"Error: Tool '{tool_name}' not available",
                "error": "tool_not_found",
            }

        try:
            # Run the tool
            tool = self.tools[tool_name]
            result = tool.execute(**args)

            # Update session context based on tool execution
            self._update_session_context(tool_name, args, result, session_ctx)

            return {"tool": tool_name, "args": args, "output": result}

        except Exception as e:
            return {
                "tool": tool_name,
                "args": args,
                "output": f"Error executing {tool_name}: {str(e)}",
                "error": "execution_failed",
            }

    def _update_session_context(
        self,
        tool_name: str,
        args: dict[str, Any],
        result: Any,
        session_ctx: dict[str, Any],
    ) -> None:
        """Updates the session context based on tool execution results.

        Args:
            tool_name: The name of the executed tool.
            args: The arguments passed to the tool.
            result: The result from the tool execution.
            session_ctx: The session context to update.
        """
        # Update last selected product for product selection tools
        if tool_name == "product_selection" and isinstance(result, dict):
            if "selected_product" in result:
                session_ctx["last_selected_product"] = result["selected_product"]

        # Track recent searches for context
        if tool_name == "product_search":
            recent_searches = session_ctx.get("recent_searches", [])
            search_query = args.get("query", "")
            if search_query and search_query not in recent_searches:
                recent_searches.append(search_query)
                # Keep only last 5 searches
                session_ctx["recent_searches"] = recent_searches[-5:]

        # Track tool usage history
        tool_history = session_ctx.get("tool_history", [])
        tool_history.append(
            {
                "tool": tool_name,
                "args": args,
                "timestamp": None,  # Could add timestamp if needed
            }
        )
        # Keep only last 10 tool calls
        session_ctx["tool_history"] = tool_history[-10:]
